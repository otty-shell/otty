use std::fmt;

/// Stable identity of a terminal block.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct BlockId(String);

impl BlockId {
    /// Return the serialized block identity.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Create an identity supplied by a trusted protocol or application path.
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// Create a terminal block identity namespaced by session and shell.
    pub fn terminal(
        session_id: &TerminalSessionId,
        shell_instance_id: &ShellInstanceId,
        sequence: u64,
    ) -> Self {
        Self(format!(
            "{}:{}:{sequence}",
            session_id.as_str(),
            shell_instance_id.as_str()
        ))
    }
}

impl fmt::Display for BlockId {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

