/// Monotonic ordering value for events emitted by one shell instance.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct ProtocolSequence(u64);

impl ProtocolSequence {
    /// Return the numeric ordering value.
    pub fn value(self) -> u64 {
        self.0
    }

    /// Create a sequence value from a validated protocol field.
    pub fn new(value: u64) -> Self {
        Self(value)
    }

    pub(super) fn next(self) -> Option<Self> {
        self.0.checked_add(1).map(Self)
    }
}

impl fmt::Display for ProtocolSequence {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.fmt(formatter)
    }
}

#[cfg(test)]
mod tests {
    use super::{
        BlockId, ProtocolSequence, ShellInstanceId, TerminalSessionId,
    };

    #[test]
    fn terminal_block_id_contains_all_identity_parts() {
        let session = TerminalSessionId::new("session-a");
        let shell = ShellInstanceId::new("shell-b");

        let id = BlockId::terminal(&session, &shell, 42);

        assert_eq!(id.as_str(), "session-a:shell-b:42");
    }

    #[test]
    fn protocol_sequence_exposes_ordering_value() {
        let first = ProtocolSequence::new(1);
        let second = ProtocolSequence::new(2);

        assert!(first < second);
        assert_eq!(second.value(), 2);
    }
}
