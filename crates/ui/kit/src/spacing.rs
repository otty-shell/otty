//! Spacing tokens for paddings and gaps, in logical pixels.

/// `space-1`: icon to label in chips, gap between segmented options.
pub const SPACE_1: f32 = 4.0;
/// `space-2`: gap between label and field, between toolbar buttons.
pub const SPACE_2: f32 = 6.0;
/// `space-3`: row inner padding, panel padding.
pub const SPACE_3: f32 = 8.0;
/// `space-4`: gap between fields, block padding, pane header padding.
pub const SPACE_4: f32 = 12.0;
/// `space-5`: block side padding, inspector padding.
pub const SPACE_5: f32 = 16.0;
/// `space-6`: gap between form sections.
pub const SPACE_6: f32 = 24.0;
/// `space-7`: form page top padding.
pub const SPACE_7: f32 = 36.0;
