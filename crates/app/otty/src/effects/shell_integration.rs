//! OTTY shell integration: writes the bundled zsh and bash scripts to a
//! folder and wires them into a shell's launch options, so the shell reports
//! its commands and current folder to the terminal.

#![allow(
    clippy::disallowed_methods,
    reason = "effects/ is where the binary writes files and starts background work"
)]

use std::path::{Path, PathBuf};
use std::{env, fs};

use iced::Task;
use otty_app_domain::shell_session::shell_name;
use otty_ui_term::settings::LocalSessionOptions;

use crate::message::AppEvent;
use crate::shell_session::{ShellSession, shell_session_options};

const SHELL_INTEGRATIONS_DIR: &str = "otty";

const OTTY_ZSH_SCRIPT: &str =
    include_str!("../../../../../assets/shell-integrations/otty.zsh");
const OTTY_BASH_SCRIPT: &str =
    include_str!("../../../../../assets/shell-integrations/otty.bash");

/// Write the shell integration files for the shell at `shell_path` in the
/// background, and send the session new terminals start to the app as
/// [`AppEvent::ShellIntegrated`].
pub(crate) fn integrate(shell_path: String) -> Task<AppEvent> {
    Task::perform(
        async move {
            integrated_shell_session(&shell_path, &shell_integration_dir())
        },
        AppEvent::ShellIntegrated,
    )
}

/// Build the session of the shell at `shell_path`, started in the home
/// folder, with the OTTY shell integration whose files are written to `dir`.
/// When the files cannot be written, the shell starts without it.
pub(crate) fn integrated_shell_session(
    shell_path: &str,
    dir: &Path,
) -> ShellSession {
    let options = shell_session_options(shell_path);

    match with_shell_integration(options, dir) {
        Ok(options) => ShellSession::from_options(shell_path, options),
        Err(err) => {
            log::warn!("shell integration setup failed: {err}");
            ShellSession::without_integration(shell_path)
        },
    }
}

/// Add the OTTY shell integration, with its files written to `dir`, to a
/// session whose program is zsh or bash, so the shell reports its commands
/// and folder. Other programs are returned unchanged.
pub(crate) fn with_shell_integration(
    options: LocalSessionOptions,
    dir: &Path,
) -> std::io::Result<LocalSessionOptions> {
    match shell_name(options.program()).as_str() {
        "zsh" => {
            fs::create_dir_all(dir)?;
            zsh_integration(options, dir)
        },
        "bash" => {
            fs::create_dir_all(dir)?;
            bash_integration(options, dir)
        },
        _ => Ok(options),
    }
}

/// Return the folder the OTTY shell integration files are written to.
pub(crate) fn shell_integration_dir() -> PathBuf {
    if let Ok(home) = env::var("HOME") {
        return Path::new(&home)
            .join(".config")
            .join(SHELL_INTEGRATIONS_DIR);
    }

    env::temp_dir().join(SHELL_INTEGRATIONS_DIR)
}

fn zsh_integration(
    options: LocalSessionOptions,
    dir: &Path,
) -> std::io::Result<LocalSessionOptions> {
    let original_zdotdir = env::var("ZDOTDIR").ok();

    let script_path = dir.join("otty.zsh");
    fs::write(&script_path, OTTY_ZSH_SCRIPT)?;

    let zshrc_path = dir.join(".zshrc");
    let zshrc_contents = r#"
# Generated by OTTY: wrapper around user zshrc
if [[ -n "${OTTY_ORIG_ZDOTDIR:-}" && "${OTTY_ORIG_ZDOTDIR}" != "${ZDOTDIR:-$HOME}" && -f "${OTTY_ORIG_ZDOTDIR}/.zshrc" ]]; then
  source "${OTTY_ORIG_ZDOTDIR}/.zshrc"
elif [[ -f "${HOME}/.zshrc" ]]; then
  source "${HOME}/.zshrc"
fi

if [[ -f "${ZDOTDIR:-$HOME}/otty.zsh" ]]; then
  source "${ZDOTDIR:-$HOME}/otty.zsh"
fi
"#;

    fs::write(&zshrc_path, zshrc_contents.trim_start())?;

    let dir_str = dir.to_string_lossy();
    let mut options = options.with_env("ZDOTDIR", dir_str.as_ref());

    if let Some(value) = original_zdotdir
        && Path::new(&value) != dir
    {
        options = options.with_env("OTTY_ORIG_ZDOTDIR", &value);
    }

    Ok(options)
}

fn bash_integration(
    options: LocalSessionOptions,
    dir: &Path,
) -> std::io::Result<LocalSessionOptions> {
    let script_path = dir.join("otty.bash");
    fs::write(&script_path, OTTY_BASH_SCRIPT)?;

    let wrapper_path = dir.join("otty.bashrc");
    let script_path_display = script_path.to_string_lossy();
    let wrapper_contents = format!(
        r#"# Generated by OTTY: wrapper around user bashrc
if [[ -f "$HOME/.bashrc" ]]; then
  source "$HOME/.bashrc"
fi

if [[ -f "{script_path_display}" ]]; then
  source "{script_path_display}"
fi
"#
    );

    fs::write(&wrapper_path, wrapper_contents.trim_start())?;

    let wrapper_path = wrapper_path.to_string_lossy().into_owned();

    Ok(options.with_args(vec!["--rcfile".to_string(), wrapper_path]))
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;
    use std::time::{SystemTime, UNIX_EPOCH};
    use std::{fs, process};

    use otty_ui_term::settings::{LocalSessionOptions, SessionKind};

    use super::{integrated_shell_session, with_shell_integration};

    struct TempDirGuard {
        path: PathBuf,
    }

    impl TempDirGuard {
        fn new(prefix: &str) -> Self {
            let stamp = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .expect("system time should be after epoch")
                .as_nanos();
            let path = std::env::temp_dir().join(format!(
                "otty-terminal-{prefix}-{}-{stamp}",
                process::id(),
            ));
            fs::create_dir_all(&path)
                .expect("failed to create temporary directory");
            Self { path }
        }
    }

    impl Drop for TempDirGuard {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.path);
        }
    }

    fn shell_options(program: &str) -> LocalSessionOptions {
        LocalSessionOptions::default()
            .with_program(program)
            .with_working_directory(PathBuf::from("/home/user/projects"))
    }

    #[cfg(unix)]
    #[test]
    fn given_bash_when_integration_added_then_wrapper_files_are_written() {
        let temp_dir = TempDirGuard::new("bash");
        let options =
            with_shell_integration(shell_options("/bin/bash"), &temp_dir.path)
                .expect("setup");

        let script_path = temp_dir.path.join("otty.bash");
        let wrapper_path = temp_dir.path.join("otty.bashrc");
        assert!(script_path.exists());
        assert!(wrapper_path.exists());
        assert_eq!(options.program(), "/bin/bash");
        assert_eq!(options.args().len(), 2);
        assert_eq!(options.args()[0], "--rcfile");
        assert_eq!(options.args()[1], wrapper_path.to_string_lossy());
        assert_eq!(
            options.working_directory(),
            &Some(PathBuf::from("/home/user/projects")),
        );
    }

    #[cfg(unix)]
    #[test]
    fn given_zsh_when_integration_added_then_wrapper_files_are_written() {
        let temp_dir = TempDirGuard::new("zsh");
        let options =
            with_shell_integration(shell_options("/bin/zsh"), &temp_dir.path)
                .expect("setup");

        let script_path = temp_dir.path.join("otty.zsh");
        let zshrc_path = temp_dir.path.join(".zshrc");
        assert!(script_path.exists());
        assert!(zshrc_path.exists());
        assert_eq!(options.program(), "/bin/zsh");
        assert_eq!(
            options.envs().get("ZDOTDIR"),
            Some(&temp_dir.path.to_string_lossy().to_string()),
        );
        assert_eq!(
            options.working_directory(),
            &Some(PathBuf::from("/home/user/projects")),
        );
    }

    #[test]
    fn given_other_program_when_integration_added_then_options_are_unchanged() {
        let temp_dir = TempDirGuard::new("htop");
        let options = LocalSessionOptions::default().with_program("htop");

        let integrated = with_shell_integration(options, &temp_dir.path)
            .expect("nothing to set up");

        assert_eq!(integrated.program(), "htop");
        assert!(integrated.args().is_empty());
        assert!(integrated.envs().get("ZDOTDIR").is_none());
        assert!(!temp_dir.path.join("otty.zsh").exists());
    }

    #[cfg(unix)]
    #[test]
    fn given_zsh_when_integrated_session_built_then_it_starts_with_the_integration()
     {
        let temp_dir = TempDirGuard::new("session-zsh");
        let home = std::env::var_os("HOME").map(PathBuf::from);

        let session = integrated_shell_session("/bin/zsh", &temp_dir.path);

        assert_eq!(session.name(), "zsh");
        let SessionKind::Local(options) = session.session() else {
            panic!("expected local session kind");
        };
        assert_eq!(options.program(), "/bin/zsh");
        assert_eq!(options.working_directory(), &home);
        assert_eq!(
            options.envs().get("ZDOTDIR"),
            Some(&temp_dir.path.to_string_lossy().to_string()),
        );
        assert!(temp_dir.path.join("otty.zsh").exists());
    }

    #[cfg(unix)]
    #[test]
    fn given_folder_that_cannot_be_created_when_integrated_session_built_then_shell_starts_without_it()
     {
        let temp_dir = TempDirGuard::new("session-blocked");
        let file = temp_dir.path.join("file");
        fs::write(&file, "").expect("failed to create a file");

        let session = integrated_shell_session("/bin/zsh", &file.join("otty"));

        assert_eq!(session.name(), "zsh");
        let SessionKind::Local(options) = session.session() else {
            panic!("expected local session kind");
        };
        assert_eq!(options.program(), "/bin/zsh");
        assert!(options.envs().get("ZDOTDIR").is_none());
    }
}
